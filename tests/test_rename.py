# --- The exit statuses of the command line.


@pytest.mark.parametrize(
    ("arguments", "message"),
    [
        (["x-lab", "x-hub"], "confirm it on a terminal, or pass --yes"),
        (["x-lab", "x-hub", "--format", "json"], "--format json prints the plan for a program"),
        (["X", "x-hub", "--dry-run"], "OLD 'X' lies outside the pattern of repository-id"),
        (["x-lab", "x-lab", "--dry-run"], "OLD and NEW are both x-lab"),
        (
            ["x-lab", "x-hub", "--dry-run", "--repository", "/"],
            "is neither the root nor a submodule",
        ),
    ],
)
def test_an_invalid_invocation_exits_with_two(
    tmp_path: Path, arguments: list[str], message: str
) -> None:
    root = _workspace(tmp_path)
    before = _snapshot(root)
    status, output = _rename(root, *arguments)
    assert status == 2, output
    # Rich colours the usage error and frames it in a box when the host forces colour, as CI does.
    plain = re.sub(r"[\u2500-\u257f]", " ", re.sub(r"\x1b\[[0-9;]*m", "", output))
    assert message in " ".join(plain.split())
    assert _snapshot(root) == before
