def test_a_registry_key_that_cannot_be_rewritten_refuses_the_rename(tmp_path: Path) -> None:
    # A key written twice reads as its last value, whereas the first one is located and edited.
    registry = RENAMED["record-registry.yml"].replace(
        "repository: x-lab\n", "repository: other\nrepository: x-lab\n"
    )
    root = _workspace(
        tmp_path, {"projects/x": {**RENAMED, "record-registry.yml": registry}, "projects/y": CITING}
    )
    before = _snapshot(root)
    status, output = _rename(
        root, "x-lab", "x-hub", "--repository", str(root / "projects/x"), "--yes"
    )
    assert status == 1, output
    assert (
        "projects/x/record-registry.yml: the key repository cannot be rewritten in place" in output
    )
    assert _snapshot(root) == before


# --- The warnings.


def test_a_target_that_cannot_be_rewritten_keeps_the_former_identifier(tmp_path: Path) -> None:
    # A TOML record is read for its targets, and is not rewritten in place.
    configuration = CITING["anagraphe.yml"].replace(
        "repository: {id: y-lab}\n",
        "repository: {id: y-lab}\nmetadata:\n  - {when: {types: [toml]}, from: {toml: [record]}}\n",
    )
    cite = (
        '_schema = "test:citing@1"\n[record]\nid = "toml-cite"\n'
        '[profile]\nrepository = "x-lab"\nid = "ada"\n'
    )
    citing = {**CITING, "anagraphe.yml": configuration, "cite.toml": cite}
    root = _workspace(tmp_path, {"projects/x": RENAMED, "projects/y": citing})
    status, output = _rename(
        root, "x-lab", "x-hub", "--repository", str(root / "projects/x"), "--yes"
    )
    assert status == 0, output
    assert (
        f"projects/y/cite.toml:1: warning: {UNREWRITABLE_TARGET}: /profile: the target keeps "
        "x-lab: a TOML document is not rewritten in place"
    ) in output
    assert (root / "projects/y/cite.toml").read_text() == cite
    assert "x-hub" in (root / "projects/y/cite.yml").read_text()


