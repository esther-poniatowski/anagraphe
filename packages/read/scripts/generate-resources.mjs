// =================================================================================================
// Generator of `src/generated/resources.ts`
//
// Writes the packaged schemas of Anagraphe into one TypeScript module, so that the package copies
// no pattern by hand. The
// scripts `generate`, `pretest`, `pretypecheck`, `prelint` and `prebuild` run it.
//
// Usage
// -----
//   node scripts/generate-resources.mjs           writes the module
//   node scripts/generate-resources.mjs --check   exits 1 when the module differs from its sources
// =================================================================================================
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const PACKAGE = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPOSITORY = join(PACKAGE, "..", "..");
const SCHEMAS = join(REPOSITORY, "src", "anagraphe", "data", "schemas");
const OUTPUT = join(PACKAGE, "src", "generated", "resources.ts");

/** The packaged schemas, each with the name of its constant. */
const SCHEMA_FILES = [
  ["ADDRESSING_SCHEMA", "addressing.v1.schema.yml"],
  ["REPOSITORY_SCHEMA", "repository.schema.yml"],
  ["RECORD_REGISTRY_SCHEMA", "record-registry.v1.schema.yml"],
];

/** Returns the text of the generated module. */
function render() {
  const source = (file) => relative(REPOSITORY, join(SCHEMAS, file));
  const blocks = SCHEMA_FILES.map(([constant, file]) => {
    // The schemas hold no scalar whose reading differs between YAML 1.1 and 1.2.
    const schema = parse(readFileSync(join(SCHEMAS, file), "utf-8"), { version: "1.1" });
    return `/** The schema \`${source(file)}\`. */\nexport const ${constant} = ${JSON.stringify(schema, null, 2)} as const;\n`;
  });
  return [
    "// Generated by scripts/generate-resources.mjs from the sources of Anagraphe; do not edit by hand.",
    "",
    blocks.join("\n"),
  ].join("\n");
}

const text = render();
if (process.argv.includes("--check")) {
  let current = null;
  try {
    current = readFileSync(OUTPUT, "utf-8");
  } catch {
    current = null;
  }
  if (current !== text) {
    console.error(`${relative(PACKAGE, OUTPUT)} differs from its sources; run npm run generate`);
    process.exit(1);
  }
} else {
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, text);
}
