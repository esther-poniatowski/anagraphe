"""
The written form of a record registry in the contract ``anagraphe:record-registry@1``.

Both mappings of a registry are keyed by identifier and written sorted, one flow mapping per line,
under a header stating that a command writes the file. The model of the contract and its reading
belong to the read distribution, so that a resolver reads a registry without the command line.
"""

from __future__ import annotations

import datetime

import yaml

from anagraphe_read._targets.registry.contract import REGISTRY_CONTRACT, RecordRegistry

#: The first line of every registry written by Anagraphe.
HEADER = "# Generated by anagraphe records write; do not edit by hand.\n"
#: The width above which the YAML writer would fold a line; no entry is folded.
_UNFOLDED = 1 << 30


def render(registry: RecordRegistry) -> str:
    """Return the written form of a registry, its mappings sorted by identifier.

    The identifiers are sorted by their characters, so that the order does not depend on the
    locale of a writer. A scalar that YAML would read as another type than a string, such as
    the identifier ``2024``, is quoted by the YAML writer.

    Examples
    --------
    >>> from anagraphe_read._targets.registry.contract import Entry, Format, Retirement
    >>> registry = RecordRegistry(
    ...     "geonexus",
    ...     {"mixture-input": Entry("notes/mixture-input.md", Format.MARKDOWN)},
    ...     {"removed-id": Retirement("2026-11-21")},
    ... )
    >>> print(render(registry), end="")
    # Generated by anagraphe records write; do not edit by hand.
    _schema: anagraphe:record-registry@1
    repository: geonexus
    records:
      mixture-input: {path: notes/mixture-input.md, format: markdown}
    retired:
      removed-id: {date: 2026-11-21}
    """
    document = {
        "_schema": REGISTRY_CONTRACT,
        "repository": registry.repository,
        "records": {
            identifier: {"path": entry.path, "format": entry.format.value}
            for identifier, entry in sorted(registry.records.items())
        },
        "retired": {
            identifier: {
                "date": datetime.date.fromisoformat(retirement.date),
                **(
                    {"replaced_by": retirement.replaced_by}
                    if retirement.replaced_by is not None
                    else {}
                ),
            }
            for identifier, retirement in sorted(registry.retired.items())
        },
    }
    body = yaml.safe_dump(
        document,
        default_flow_style=None,
        sort_keys=False,
        width=_UNFOLDED,
        allow_unicode=True,
    )
    return HEADER + body
